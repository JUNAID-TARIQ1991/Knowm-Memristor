            # Calculate waveform parameters, Triangular waveform
            sample_num = 256  # Number of samples per pulse
            byte_samples = bytearray(2 * sample_num)

            for i in range(sample_num):
                if i < sample_num // 2:
                    # First half: NEGATIVE triangular ramp
                    # from 0 -> -1 -> back to 0
                    x = i / (sample_num // 2)
                    tri = -1.0 + 2.0 * x      # -1 → +1
                else:
                    # Second half: POSITIVE triangular ramp
                    x = (i - sample_num // 2) / (sample_num // 2)
                    tri = 1.0 - 2.0 * x       # +1 → -1

                # Map [-1, +1] → [0, 32767]
                dac = int((tri + 1.0) * 16383)

                # Safety clamp
                dac = max(0, min(32767, dac))

                # Little-endian packing
                byte_samples[2 * i]     = dac & 0xFF
                byte_samples[2 * i + 1] = (dac >> 8) & 0xFF

            #print(f"Configuring AWG channel {selected_channel}...")

