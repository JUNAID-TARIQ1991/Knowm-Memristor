            # To Plot the samples
            # waveformbytes = AWG.query_binary_values( f'TRACe{selected_channel}:DATA? CAR', datatype='B')
            # Plot_Samples(waveformbytes)

            # Set arbitrary waveform
            write_cmd(f"SOURce{selected_channel}:FUNCtion:SHAPe ARBB")

            # Set Amplitude

            if amplitude > 0:
                # write_cmd(f"SOURce{selected_channel}:VOLTage:AMPLitude {amplitude}")
                write_cmd(f"SOURce{selected_channel}:VOLTage:HIGH {amplitude}")
                write_cmd(f"SOURce{selected_channel}:VOLTage:LOW 0")

                # Set offset, both of the following commands work
                write_cmd(
                    f"SOURce{selected_channel}:VOLTage:OFFSet {amplitude/2}")
                #write_cmd(f"SOURce{selected_channel}:VOLTage:OFFSet 0")
                # write_cmd(f"SOURce{selected_channel}:VOLTage:LEVel:IMMediate:OFFSet {amplitude/2}")
            else:
                write_cmd(f"SOURce{selected_channel}:VOLTage:HIGH 0")

