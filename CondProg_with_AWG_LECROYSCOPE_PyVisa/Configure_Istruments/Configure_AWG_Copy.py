            #     byte_samples[2 * i + 1] = (scaled >> 8) & 0xFF  # Upper byte
            
            print(f"Configuring AWG channel {selected_channel}...")

            # Disable the output for the channel
            write_cmd(f"OUTPut{selected_channel}:STATe 0")

            # Set the voltage limit for each channel
            write_cmd(f"SOURce{selected_channel}:VOLTage:LIMit:HIGH 100mV ")

            # Sets the channel load impedance to maximum
            write_cmd(f"OUTPut{selected_channel}:LOAd MAXimum")

            # print("Buffer for TRACE expects n points:\n", AWG.query(f'TRACE{selected_channel}:POINTS?'))

            # Send waveform data to the channel
            str_cmd = f'TRACe{selected_channel}:DATA CAR,'
            # AWG.write_binary_values(str_cmd, byte_samples, datatype='B', is_big_endian=True)
            AWG.write_binary_values(str_cmd, byte_samples, datatype='B')

