    def Plot_Samples(waveformbytes):

        waveform_data = np.empty(int(len(waveformbytes)/2))

        for i in range(0, len(waveform_data)):
            waveform_data[len(waveform_data) - i -
                          1] = waveformbytes[2*i] + waveformbytes[2*i+1]*256

        # Convert waveform data to numpy array for visualization
        # Plot the waveform
        plt.figure()
        plt.plot(waveform_data)  # Plot the first 1000 points for visibility
        plt.title("Pulse Waveform Generated by AWG")
        plt.xlabel("Time (s)")
        plt.ylabel("Amplitude (V)")
        plt.grid(True)
        plt.show()
    # end of def Plot_Samples(waveformbytes):

